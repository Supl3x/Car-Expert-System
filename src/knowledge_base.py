"""Knowledge base: 86 explicit IF-THEN rules.

Every rule is a dictionary. The IF part is built with C(...):
    yes     -> facts that must be "Yes"
    no      -> facts that must be "No"
    derived -> facts that must have been derived by earlier rules (forward chaining)
An "Unknown" answer never satisfies a condition, so unknown never counts as a finding.
"""


def _t(x):
    return (x,) if isinstance(x, str) else tuple(x)


def C(yes=(), no=(), derived=()):
    yes, no, derived = _t(yes), _t(no), _t(derived)

    def cond(f):
        return (all(f.get(k) == "Yes" for k in yes)
                and all(f.get(k) == "No" for k in no)
                and all(f.get(k) is True for k in derived))

    parts = [f"{k} = Yes" for k in yes] + [f"{k} = No" for k in no] + [f"{d} (derived)" for d in derived]
    cond.yes, cond.no, cond.derived = yes, no, derived
    cond.text = " AND ".join(parts)
    return cond


def R(rid, cat, desc, cond, concl, sev, expl, rec, typ="negative", derive=None, suppress_if=None):
    return {"id": rid, "category": cat, "description": desc, "condition": cond,
            "conclusion": concl, "severity": sev, "type": typ, "explanation": expl,
            "recommendation": rec, "derived_fact": derive, "suppress_if": suppress_if}


